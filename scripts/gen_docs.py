#!/usr/bin/env python3
"""Catalog documents generated from the data files.

Usage: python3 scripts/gen_docs.py   (after extract_statements.py and build_graph.py)

Writes
  docs/SOURCE_MANIFEST.md      the four PDFs: hashes, dates, publication data
  docs/STATEMENT_CATALOG.md    every statement, grouped by paper and section
  docs/REFERENCE_INVENTORY.md  every bibliography key, citation counts, critical-path use
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROMAN = {1: "I", 2: "II", 3: "III", 4: "IV"}


def load(name):
    return json.loads((ROOT / "data" / name).read_text())


def table(rows, header):
    esc = lambda c: str("" if c is None else c).replace("|", "\\|")
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def pages(s):
    a, b = s.get("pdf_page"), s.get("pdf_page_end")
    if a is None:
        src = s.get("source")
        return str(src.get("pdf_pages", "")) if isinstance(src, dict) else ""
    return str(a) if b in (None, a) else f"{a} to {b}"


def manifest_doc(manifest):
    doc = ["# Source manifest", "",
           "Generated by `scripts/gen_docs.py` from `data/source_manifest.json`, which "
           "`scripts/extract_statements.py` computes from the PDFs. Do not edit by hand.", "",
           "The PDFs in hand are the author's manuscript versions, dated on their title pages "
           "as below. They are not the journal typesetting: page numbers in this project are "
           "manuscript page numbers (in these files the PDF page number equals the printed "
           "page number), and they differ from the journal pagination listed under "
           "Publication. The publication data was checked by resolving each DOI at doi.org "
           "and reading its Crossref record; the check date is recorded with each entry.", ""]
    for m in manifest:
        pub = m["publication"]
        doc += [f"## IUT {ROMAN[m['paper']]} (`{m['citation_key']}`)", "",
                table([
                    ["File", f"`{m['file']}`"],
                    ["SHA-256", f"`{m['sha256']}`"],
                    ["Size", f"{m['bytes']} bytes"],
                    ["PDF pages", m["pdf_pages"]],
                    ["Date on the title page", m["title_page_date"]],
                    ["PDF creation date", m["pdf_creation_date"]],
                    ["PDF title field", m["pdf_title"]],
                    ["PDF producer", m["pdf_producer"]],
                    ["PDF page equals printed page", "yes" if m["pdf_page_equals_printed_page"]
                     else "no"],
                    ["Pages without a printed number", m["pages_without_printed_number"]],
                    ["Numbered statements indexed", m["numbered_statements"]],
                    ["Lettered results indexed", m["lettered_results"]],
                    ["Version in hand", pub["version_in_hand"]],
                    ["Journal", pub["journal"]],
                    ["Volume, issue, year", f"{pub['volume']}, {pub['issue']}, {pub['year']}"],
                    ["Journal pages", pub["pages"].replace("-", " to ")],
                    ["Publisher", pub["publisher"]],
                    ["DOI", f"[{pub['doi']}](https://doi.org/{pub['doi']})"],
                    ["Print publication date (Crossref)", pub["crossref_published_print"]],
                    ["Verification", pub["verified"]],
                ], ["Field", "Value"]), ""]
    return "\n".join(doc)


def catalog_doc(statements, critical):
    children = defaultdict(list)
    for s in statements:
        if s.get("parent"):
            children[s["parent"]].append(s)
    doc = ["# Statement catalog", "",
           "Generated by `scripts/gen_docs.py` from `data/statements.json`. Do not edit by hand.",
           "", "Every numbered statement and every lettered result of the Introductions, "
           "grouped by paper and section, with the curated parts and proof steps under their "
           "parent. Titles are the parenthesized titles of the papers (for examples, the "
           "title phrase after the number), read from the PDF text layer only: subscripts, superscripts "
           "and some symbols of the printed titles are dropped or flattened. Statuses: NOT_EXTRACTED means that only the "
           "mechanical index has seen the statement. \"Path\" marks the critical path of "
           "`docs/CRITICAL_PATH.md`.", ""]
    header = ["Id", "Kind", "Title", "PDF pages", "Statement", "Proof", "Lean declaration",
              "Path"]
    for paper in range(1, 5):
        doc += [f"## IUT {ROMAN[paper]}", ""]
        sections = defaultdict(list)
        for s in statements:
            if s.get("paper") == paper and not s.get("parent"):
                sections[(s.get("section") or 0, s.get("section_title") or "")].append(s)
        for (num, title), group in sorted(sections.items()):
            doc += [f"### Section {num}: {title}" if num else f"### {title}", ""]
            rows = []

            def add(s, depth):
                lean = s.get("lean_declaration")
                rows.append(["&nbsp;&nbsp;" * depth + f"`{s['id']}`", s.get("kind") or "part",
                             s.get("title") or "", pages(s), s.get("statement_status"),
                             s.get("proof_status"), f"`{lean}`" if lean else "",
                             "yes" if s["id"] in critical else ""])
                for c in sorted(children[s["id"]], key=lambda c: c["id"]):
                    add(c, depth + 1)

            for s in sorted(group, key=lambda s: (s.get("pdf_page") or 0, s["id"])):
                add(s, 0)
            doc += [table(rows, header), ""]
    orphans = [s for s in statements if s.get("parent")
               and s["parent"] not in {t["id"] for t in statements}]
    if orphans:
        doc += ["## Curated records whose parent is not indexed", "",
                table([[f"`{s['id']}`", s["parent"]] for s in orphans], ["Id", "Parent"]), ""]
    return "\n".join(doc)


def references_doc(references, statements, critical):
    cited_by = defaultdict(set)
    for s in statements:
        if s["id"] in critical:
            for key in s.get("external_keys") or {}:
                cited_by[key].add(s["id"])
    doc = ["# Reference inventory", "",
           "Generated by `scripts/gen_docs.py` from `data/references.json` and "
           "`data/dependency_graph.json`. Do not edit by hand.", "",
           "Every key that appears in the bibliography of one of the four papers. The columns "
           "IUT1 to IUT4 count bracketed occurrences of the key in the text before each "
           "paper's bibliography (counted mechanically; a key cited twice in one sentence counts "
           "twice). The last column lists the critical-path statements whose statement or proof "
           "text cites the key.", ""]
    rows = []
    for r in references:
        crit = sorted(cited_by.get(r["key"], ()))
        rows.append([f"`{r['key']}`", r["entry"] or ""]
                    + [r["cited_in"].get(f"IUT{p}", 0) for p in range(1, 5)]
                    + [", ".join(f"`{i}`" for i in crit)])
    doc.append(table(rows, ["Key", "Entry", "IUT1", "IUT2", "IUT3", "IUT4",
                            "Cited by critical-path statements"]))
    return "\n".join(doc)


def main():
    manifest = load("source_manifest.json")
    statements = load("statements.json")
    references = load("references.json")
    critical = set(load("dependency_graph.json")["analysis"]["critical_path"])
    docs = ROOT / "docs"
    (docs / "SOURCE_MANIFEST.md").write_text(manifest_doc(manifest) + "\n")
    (docs / "STATEMENT_CATALOG.md").write_text(catalog_doc(statements, critical) + "\n")
    (docs / "REFERENCE_INVENTORY.md").write_text(
        references_doc(references, statements, critical) + "\n")
    print(f"docs: {len(manifest)} sources, {len(statements)} statements, "
          f"{len(references)} references")


if __name__ == "__main__":
    main()
